# Step 1: Import the math module.
import math
# Step 2: Use math.ceil(23.56) and math.floor(23.56) to round the same number up and down, printing both results.
print(math.ceil(23.56))
print(math.floor(23.56))
# Step 3: Set x to 10 and y to -15.
x= 10
y= -15
# Step 4: Use math.copysign(x, y) to copy y's negative sign onto x, printing the result.
print(math.copysign(x,y))
# Step 5: Use math.fabs(-96) and math.fabs(56) to find two absolute values, printing both results.
print(math.fabs(-96))
print(math.fabs(56))
# Step 6: Use math.gcd(24, 56) to find the greatest common divisor of 24 and 56, printing the result.
print(math.gcd(24,56))